const DICT = { fr, nouchi, en, es, pt, ar, zh };

let current = 'fr';

export function locale() { return current; }

export function setLocale(id) {
  if (!DICT[id]) id = 'fr';
  current = id;
  const meta = LOCALES.find((l) => l.id === id) || LOCALES[0];
  const r = document.documentElement;
  r.lang = id === 'nouchi' ? 'fr' : id;
  r.dir = meta.dir;
  return id;
}

export function syncFromSettings() {
  return setLocale(store.settings().locale || 'fr');
}

/** t('key', {n: 3}) — repli : langue courante → français → clé brute. */
export function t(key, vars) {
  const d = DICT[current] || {};
  let s = d[key];
  if (s == null) s = fr[key];
  if (s == null) s = key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v));
  }
  return s;
}

export function dirOf(id) {
  const meta = LOCALES.find((l) => l.id === id);
  return meta ? meta.dir : 'ltr';
}

