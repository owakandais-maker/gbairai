const intlLocale = () => (current === 'nouchi' ? 'fr-CI' : current);

export function nfmt(n) {
  const v = Number(n) || 0;
  if (Math.abs(v) >= 1e9) return (v / 1e9).toFixed(1).replace(/\.0$/, '') + ' G';
  if (Math.abs(v) >= 1e6) return (v / 1e6).toFixed(1).replace(/\.0$/, '') + ' M';
  if (Math.abs(v) >= 1e4) return (v / 1e3).toFixed(1).replace(/\.0$/, '') + ' k';
  try { return new Intl.NumberFormat(intlLocale()).format(v); } catch (e) { return String(v); }
}

const CUR = { XOF: { s: 'F CFA', d: 0 }, EUR: { s: '€', d: 2 }, USD: { s: '$', d: 2 }, GHS: { s: 'GH₵', d: 2 }, NGN: { s: '₦', d: 0 }, TARO: { s: 'TARO', d: 0 } };

export function money(n, cur) {
  const code = cur || store.settings().currency || 'XOF';
  const meta = CUR[code] || CUR.XOF;
  const v = Number(n) || 0;
  let num;
  try { num = new Intl.NumberFormat(intlLocale(), { minimumFractionDigits: meta.d, maximumFractionDigits: meta.d }).format(v); }
  catch (e) { num = v.toFixed(meta.d); }
  return code === 'EUR' || code === 'USD' ? num + ' ' + meta.s : num + ' ' + meta.s;
}

export const CURRENCIES = Object.keys(CUR);

export function ago(ts) {
  const diff = Math.max(0, Date.now() - Number(ts || 0));
  const min = Math.floor(diff / 60000);
  if (min < 1) return t('time.now');
  if (min < 60) return t('time.min', { n: min });
  const hr = Math.floor(min / 60);
  if (hr < 24) return t('time.hour', { n: hr });
  const d = Math.floor(hr / 24);
  if (d < 7) return t('time.day', { n: d });
  return t('time.week', { n: Math.floor(d / 7) });
}

export function dateFmt(ts, opts) {
  try { return new Intl.DateTimeFormat(intlLocale(), opts || { day: '2-digit', month: 'short', year: 'numeric' }).format(new Date(ts)); }
  catch (e) { return new Date(ts).toISOString().slice(0, 10); }
}

export function clockGMT(d) {
  const dt = d || new Date();
  const p = (n) => String(n).padStart(2, '0');
  return p(dt.getUTCHours()) + ':' + p(dt.getUTCMinutes()) + ' GMT';
}

export function dur(sec) {
  const s = Math.max(0, Math.floor(Number(sec) || 0));
  const m = Math.floor(s / 60);
  const r = s % 60;
  return m + ':' + String(r).padStart(2, '0');
}
