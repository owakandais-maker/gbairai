const FALLBACK = 'fr';
let current = FALLBACK;

export function meta(code = current) {
  return LOCALES.find((l) => l.code === code) || LOCALES[0];
}

export function getLocale() { return current; }

export function setLocale(code) {
  current = DICT[code] ? code : FALLBACK;
  const m = meta(current);
  document.documentElement.lang = current;
  document.documentElement.dir = m.dir;
  return current;
}

/** Detect from stored value, then navigator, then fallback. */
export function detectLocale(stored) {
  if (stored && DICT[stored]) return stored;
  for (const tag of navigator.languages || [navigator.language || '']) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (DICT[base]) return base;
  }
  return FALLBACK;
}

/**
 * Translate. `vars` values are interpolated into {placeholders}.
 * Returns the key itself if nothing is found, so a missing string is visible
 * in development rather than rendering as empty space.
 */
export function t(key, vars) {
  const raw = DICT[current]?.[key] ?? DICT[FALLBACK]?.[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m
  );
}

/** Number formatting bound to the active locale. */
export function num(value, opts) {
  try { return new Intl.NumberFormat(meta().speech, opts).format(value); }
  catch { return String(value); }
}

/** Relative time ("2 h ago") bound to the active locale. */
export function ago(timestamp) {
  const diff = Date.now() - timestamp;
  if (diff < 45_000) return t('common.now');
  const units = [
    ['year', 31_536_000_000], ['month', 2_592_000_000], ['day', 86_400_000],
    ['hour', 3_600_000], ['minute', 60_000],
  ];
  try {
    const rtf = new Intl.RelativeTimeFormat(meta().speech, { numeric: 'auto' });
    for (const [unit, ms] of units) {
      if (Math.abs(diff) >= ms) return rtf.format(-Math.round(diff / ms), unit);
    }
    return rtf.format(-Math.round(diff / 1000), 'second');
  } catch {
    return new Date(timestamp).toLocaleDateString();
  }
}

/** Short clock time for chat bubbles. */
export function clock(timestamp) {
  try {
    return new Intl.DateTimeFormat(meta().speech, { hour: '2-digit', minute: '2-digit' })
      .format(timestamp);
  } catch { return ''; }
}

/** Apply translations to every [data-i18n*] node in a subtree. */
export function localise(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  const attrMap = {
    'i18nPlaceholder': 'placeholder',
    'i18nLabel': 'aria-label',
    'i18nTitle': 'title',
  };
  for (const [dataKey, attr] of Object.entries(attrMap)) {
    root.querySelectorAll(`[data-${dataKey.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}]`)
      .forEach((el) => el.setAttribute(attr, t(el.dataset[dataKey])));
  }
}
